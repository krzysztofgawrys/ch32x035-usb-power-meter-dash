/**
 * Writes dockview's stylesheet out to src/dockview.css.
 *
 * dockview-core ships no .css file. The stylesheet exists only as a string
 * literal inside the UMD bundle, which injects it into <head> at runtime - and
 * the ESM entry point, the one a bundler actually resolves, carries no styles
 * at all. So importing the package the normal way gives an unstyled, unusable
 * layout.
 *
 * Runtime injection would also mean a <style> element appearing from
 * JavaScript, which is the kind of thing a Content-Security-Policy stops. This
 * app has no CSP today, but depending on its absence is not a plan.
 *
 * Pulling the string out once gives a normal Vite asset instead: content
 * hashed, cached, diffable in review, and overridable by our own variables.
 *
 * Run after changing the dockview version:  npm run dockview:css
 */

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const pkg = require("dockview-core/package.json");
const bundle = require.resolve("dockview-core/dist/dockview-core.js");
const OUT = new URL("../src/dockview.css", import.meta.url);

const src = readFileSync(bundle, "utf8");

// Anchor on a rule that has to be in any build, then widen to the enclosing
// string literal. Anchoring on the literal's start instead would mean guessing
// which of several thousand strings it is.
const anchor = src.indexOf(".dv-dockview {");
if (anchor < 0) throw new Error("no .dv-dockview rule in the bundle - has the packaging changed?");

/** A quote preceded by an even number of backslashes ends the literal. */
const unescaped = (pos) => {
  let n = 0;
  for (let k = pos - 1; k >= 0 && src[k] === "\\"; k--) n++;
  return n % 2 === 0;
};

let start = anchor;
do { start = src.lastIndexOf('"', start - 1); } while (start > 0 && !unescaped(start));
let end = anchor;
do { end = src.indexOf('"', end + 1); } while (end > 0 && !unescaped(end));
if (start < 0 || end < 0) throw new Error("could not find the stylesheet literal");

// JSON.parse handles the escapes exactly as the JS engine would.
const css = JSON.parse(src.slice(start, end + 1));
if (!css.includes(".dv-dockview {")) throw new Error("extracted text is not the stylesheet");

const header =
  `/* Generated by scripts/extract-dockview-css.mjs from dockview-core ${pkg.version}.\n` +
  ` * Do not edit: run \`npm run dockview:css\` after changing the version.\n` +
  ` * Colours are overridden from src/style.css, not here. */\n`;

writeFileSync(OUT, header + css);
console.log(`src/dockview.css <- dockview-core ${pkg.version}: ` +
            `${css.length} chars, ${(css.match(/\{/g) ?? []).length} rules`);
